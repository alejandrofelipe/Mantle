<#
.SYNOPSIS
  Applies a rename map (mechanical old -> new renames between Minecraft versions) to Java sources.

.DESCRIPTION
  Reads a map file and applies its rules, in file order, to every file under -Root matching -Include.
  Default is a DRY RUN: nothing is written; the script prints hit counts per rule and per file, a WARNING
  list of hits that look like they fall inside a Java string literal, and a summary line
      rules=<n> files=<n> hits=<n> stringHits=<n>
  With -Apply the changed files are rewritten. Each file keeps its encoding (UTF-8, with a BOM only if it
  already had one) and its line endings (CRLF/LF are never normalized). Unchanged files are not touched.

  MAP FORMAT (one rule per line):
      <kind> <old> <new>
  - Blank lines and lines whose first non-space character is '#' are ignored. Trailing comments are NOT
    supported (they make the line have more than three fields, which is a syntax error).
  - Fields are separated by whitespace, so <old>/<new> cannot contain spaces.
  - kind 'token'   : whole-word replacement. <old> is matched literally with the regex
                     (?<![\w$])OLD(?![\w$]) - so 'token ResourceLocation Identifier' renames
                     ResourceLocation but leaves ResourceLocationLoadable, MyResourceLocation and
                     RESOURCE_LOCATION alone.
  - kind 'literal' : exact (case-sensitive) substring replacement, e.g. a full import FQN or a call
                     prefix like 'readResourceLocation('.
  - kind 'class'   : a class that moved and/or was renamed; <old>/<new> are FQNs, '$' marks a nested class
                     (a.b.Outer$Inner). In every file the dotted FQN is replaced as a whole word
                     ((?<![\w$.])OLD(?![\w$]): imports, static imports, inline FQNs, javadoc). When the simple name
                     changed, it is also replaced as a whole word (not after a '.') - but ONLY in files that import
                     the old class (single-type import), so a same-named class of another package is never touched
                     (MC 26.1.2: old client.resources.model.Material -> sprite.SpriteId vs Tinkers' own Material).
                     For a nested class, files importing the old outer class get 'Outer.Inner' -> 'NewOuter.NewInner'
                     (plus 'import NewOuter;' when the nested class moved under another top-level class).
                     Wildcard imports are not followed. Generated by FindApiRenames.java (Find-ApiRenames.ps1).
  - kind 'field'   : a static field that moved or became an expression: <old> = <owner FQN>.<NAME>, <new> = an
                     expression starting with a class FQN (EntityTypes.PIG, Items.DYE.pick(DyeColor.RED)). 'Owner.NAME'
                     is rewritten only in files importing the old owner, the FQN form everywhere; the expression's class
                     FQNs become simple names + imports (FQN kept on a simple-name clash - imported/declared in the file,
                     or a class of the file's package / a wildcard-imported package among the scanned sources; no import
                     in the same package or under a wildcard of it; no import when every hit is in a string/comment).
                     A static import is rewritten only for a plain 'Class.FIELD' expression, else reported.
  - Rules apply in file order, each on the output of the previous ones: put specific rules (import FQNs,
    longer names) before the general token rule.

  The string-literal check is a heuristic: a hit is flagged when an odd number of unescaped '"' precede it
  on its line (char literals like '"' are skipped). Flagged hits are still counted and still replaced with
  -Apply; review them in the diff.

  Exit codes: 0 = success, 1 = bad arguments (missing root/map) or unreadable file, 2 = bad map syntax.

.EXAMPLE
  pwsh -NoProfile -File Invoke-RenameMap.ps1 -Root "C:\...\repo" -Map maps\1.21.11.txt
  pwsh -NoProfile -File Invoke-RenameMap.ps1 -Root "C:\...\repo" -Map maps\1.21.11.txt -Apply
#>
[CmdletBinding()]
param(
  [Parameter(Mandatory)] [string] $Root,
  [Parameter(Mandatory)] [string] $Map,
  [switch] $Apply,
  # Glob(s) relative to -Root; '**' matches any number of directories. Comma-separated values are split
  # too, so '-Include "src/main/**/*.java,src/test/**/*.java"' works through 'pwsh -File'.
  [string[]] $Include = @('src/**/*.java'),
  # How many files to list in the per-file table.
  [int] $Top = 20
)

$ErrorActionPreference = 'Stop'
Set-StrictMode -Version Latest

# ---------- arguments ----------
if (-not (Test-Path -LiteralPath $Root -PathType Container)) { Write-Host "ERROR: root not found: $Root"; exit 1 }
if (-not (Test-Path -LiteralPath $Map -PathType Leaf)) { Write-Host "ERROR: map not found: $Map"; exit 1 }
$Root = (Resolve-Path -LiteralPath $Root).ProviderPath.TrimEnd('\', '/')
$Map = (Resolve-Path -LiteralPath $Map).ProviderPath

# ---------- field rules ----------
$fqnRefRx = [regex]::new('(?<![\w$.])([a-z_]\w*(?:\.[a-z_]\w*)*\.[A-Z]\w*(?:\$[A-Za-z_]\w*)*)')
# Instance members of the collection types a constant can be folded into (MC 26.2 WeatheringCopperCollection: the record
# accessors weathering/waxed + asList/forEach/map/apply/zipUnwaxedWaxed; ColorCollection#pick). A same-name field rule
# never rewrites 'Owner.NAME.<one of these>': that use is already the new collection.
$collectionMembers = @('weathering', 'waxed', 'asList', 'forEach', 'map', 'apply', 'zipUnwaxedWaxed', 'pick')
# 'field <owner.Fqn>.<NAME> <expression>': regexes and the class references of the expression (imported where used).
function Get-FieldRule([string] $old, [string] $new) {
  $i = $old.LastIndexOf('.')
  $owner = $old.Substring(0, $i); $name = $old.Substring($i + 1)
  $ownerDot = $owner.Replace('$', '.')
  $ownerTop = if ($owner.Contains('$')) { $owner.Substring(0, $owner.IndexOf('$')) } else { $owner }
  $ownerQual = $owner.Substring($ownerTop.LastIndexOf('.') + 1).Replace('$', '.')
  $ownerSimple = $ownerQual.Substring($ownerQual.LastIndexOf('.') + 1)
  $simpleExpr = $new -cmatch '^[a-z_]\w*(\.[a-z_]\w*)*\.[A-Z]\w*(\$[A-Za-z_]\w*)*\.[A-Za-z_]\w*$'
  # same-name rule (COPPER_BLOCK -> COPPER_BLOCK.weathering().unaffected()): never rewrite an already rewritten use. The
  # sibling rules of the family write other accessors of the same field (WAXED_COPPER_BLOCK -> COPPER_BLOCK.waxed()...),
  # so the guard covers every member of the collection types, not just this rule's first segment.
  $guard = ''
  if ($new.StartsWith("$owner.$name.")) {
    $seg = [regex]::Match($new.Substring($owner.Length + $name.Length + 2), '^[A-Za-z_]\w*').Value
    $members = @($seg) + $collectionMembers | Select-Object -Unique | ForEach-Object { [regex]::Escape($_) }
    $guard = '(?!\s*\.\s*(?:' + ($members -join '|') + ')(?![\w$]))'
  }
  $tail = '\s*\.\s*' + [regex]::Escape($name) + '(?![\w$])' + $guard
  # the FQN form everywhere; with an expression that is not 'Class.FIELD', never inside 'import static' (reported instead)
  $fqnPattern = '(?<![\w$.])' + [regex]::Escape($ownerDot) + $tail
  if (-not $simpleExpr) { $fqnPattern = '(?m)(?<!^[ \t]*import[ \t]+static[ \t][^\r\n]*)' + $fqnPattern }
  $quals = @([pscustomobject]@{ Import = [regex]::new('(?m)^\s*import\s+' + [regex]::Escape($ownerDot) + '\s*;'); Text = $ownerSimple })
  if ($owner.Contains('$')) { $quals += [pscustomobject]@{ Import = [regex]::new('(?m)^\s*import\s+' + [regex]::Escape($ownerTop) + '\s*;'); Text = $ownerQual } }
  foreach ($q in $quals) { $q | Add-Member Pattern ([regex]::new('(?<![\w$.])' + [regex]::Escape($q.Text) + $tail)) }
  $refs = foreach ($m in $fqnRefRx.Matches($new)) {
    $fqn = $m.Groups[1].Value
    $top = if ($fqn.Contains('$')) { $fqn.Substring(0, $fqn.IndexOf('$')) } else { $fqn }
    $topSimple = $top.Substring($top.LastIndexOf('.') + 1)
    [pscustomobject]@{
      Fqn = $fqn; Dot = $fqn.Replace('$', '.'); Top = $top; Pkg = $top.Substring(0, $top.LastIndexOf('.'))
      Qual = $fqn.Substring($top.LastIndexOf('.') + 1).Replace('$', '.'); TopSimple = $topSimple
      Imported = [regex]::new('(?m)^\s*import\s+(' + [regex]::Escape($top) + '|' + [regex]::Escape($top.Substring(0, $top.LastIndexOf('.'))) + '\.\*)\s*;')
      Clash = [regex]::new('(?m)(^\s*import\s+[\w.]+\.' + $topSimple + '\s*;)|((?<![\w$.])(class|interface|enum|record)\s+' + $topSimple + '(?![\w$]))')
    }
  }
  [pscustomobject]@{
    Owner = $owner; Name = $name; FqnPattern = $fqnPattern; NewFull = $new.Replace('$', '.'); Quals = $quals; Refs = @($refs)
    StaticImport = [regex]::new('(?m)^\s*import\s+static\s+' + [regex]::Escape($ownerDot) + '\.' + [regex]::Escape($name) + '\s*;')
    SimpleExpr = $simpleExpr
  }
}

# The expression for one file: class FQNs become their (qualified) simple names, imported unless the file is in the class's
# package or another class of that simple name is visible there (then the FQN stays): imported or declared in the file, a
# top-level class of the file's own package, or of a package it imports with a wildcard. The last two are only known for
# packages whose sources are under -Root/-Include ($typesByPkg); a wildcard import of an outside package is not checked.
$wildcardRx = [regex]::new('(?m)^\s*import\s+([\w.]+)\.\*\s*;')
function Test-SimpleNameVisible([string] $simple, [string] $content, [string] $pkg, [string] $exceptPkg) {
  $pkgs = @($pkg) + @($wildcardRx.Matches($content) | ForEach-Object { $_.Groups[1].Value })
  foreach ($p in $pkgs) { if ($p -ne $exceptPkg -and $typesByPkg.ContainsKey($p) -and $typesByPkg[$p].Contains($simple)) { return $true } }
  return $false
}
function Get-FieldExpression($field, [string] $content, [string] $pkg) {
  $imports = [System.Collections.Generic.List[string]]::new()
  $expr = $field.NewFull
  foreach ($r in $field.Refs | Sort-Object { $_.Dot.Length } -Descending) {
    $short = $r.Qual
    if ($pkg -ne $r.Pkg -and -not $r.Imported.IsMatch($content)) {
      if ($r.Clash.IsMatch($content) -or (Test-SimpleNameVisible $r.TopSimple $content $pkg $r.Pkg)) { $short = $r.Dot } else { $imports.Add("import $($r.Top);") }
    }
    $expr = [regex]::Replace($expr, '(?<![\w$.])' + [regex]::Escape($r.Dot) + '(?![\w$])', $short.Replace('$', '$$'))
  }
  [pscustomobject]@{ Text = $expr; Imports = $imports }
}

# ---------- parse map ----------
$rules = [System.Collections.Generic.List[object]]::new()
$errors = [System.Collections.Generic.List[string]]::new()
$lineNo = 0
foreach ($raw in [System.IO.File]::ReadAllLines($Map)) {
  $lineNo++
  $text = $raw.Trim()
  if ($text.Length -eq 0 -or $text.StartsWith('#')) { continue }
  $fields = $text -split '\s+'
  if ($fields.Count -ne 3) { $errors.Add("line ${lineNo}: expected '<kind> <old> <new>', got: $raw"); continue }
  $kind, $old, $new = $fields
  $opts = [System.Text.RegularExpressions.RegexOptions]::CultureInvariant
  $class = $null; $field = $null
  if ($kind -ceq 'token') { $pattern = '(?<![\w$])' + [regex]::Escape($old) + '(?![\w$])' }
  elseif ($kind -ceq 'literal') { $pattern = [regex]::Escape($old) }
  elseif ($kind -ceq 'class') {
    $fqnRx = '^[A-Za-z_]\w*(\.[A-Za-z_]\w*)+(\$[A-Za-z_]\w*)*$'
    if ($old -cnotmatch $fqnRx -or $new -cnotmatch $fqnRx) {
      $errors.Add("line ${lineNo}: class rule needs two FQNs (a.b.C, a.b.Outer`$Inner): $raw"); continue
    }
    $oldDot = $old.Replace('$', '.'); $newDot = $new.Replace('$', '.')
    $pattern = '(?<![\w$.])' + [regex]::Escape($oldDot) + '(?![\w$])'
    # qualified simple name = the part after the package (Outer or Outer.Inner); its last segment = the class itself
    $oldTop = if ($old.Contains('$')) { $old.Substring(0, $old.IndexOf('$')) } else { $old }
    $newTop = if ($new.Contains('$')) { $new.Substring(0, $new.IndexOf('$')) } else { $new }
    $oldQual = $old.Substring($oldTop.LastIndexOf('.') + 1).Replace('$', '.')
    $newQual = $new.Substring($newTop.LastIndexOf('.') + 1).Replace('$', '.')
    $oldSimple = $oldQual.Substring($oldQual.LastIndexOf('.') + 1)
    $newSimple = $newQual.Substring($newQual.LastIndexOf('.') + 1)
    $class = [pscustomobject]@{
      Import      = [regex]::new('(?m)^\s*import\s+' + [regex]::Escape($oldDot) + '\s*;', $opts)
      Simple      = if ($oldSimple -cne $newSimple) { [regex]::new('(?<![\w$.])' + [regex]::Escape($oldSimple) + '(?![\w$])', $opts) } else { $null }
      NewSimple   = $newSimple
      OuterImport = if ($old.Contains('$')) { [regex]::new('(?m)^\s*import\s+' + [regex]::Escape($oldTop) + '\s*;', $opts) } else { $null }
      Qual        = if ($old.Contains('$') -and $oldQual -cne $newQual) { [regex]::new('(?<![\w$.])' + [regex]::Escape($oldQual) + '(?![\w$])', $opts) } else { $null }
      NewQual     = $newQual
      NewTopImport = if ($old.Contains('$') -and $oldTop -cne $newTop) { "import $($newTop.Replace('$', '.'));" } else { $null }
    }
    $old = $oldDot; $new = $newDot
  }
  elseif ($kind -ceq 'field') {
    $ownerRx = '^[a-z_]\w*(\.[a-z_]\w*)*\.[A-Z]\w*(\$[A-Za-z_]\w*)*'
    if ($old -cnotmatch ($ownerRx + '\.[A-Za-z_]\w*$') -or $new -cnotmatch $ownerRx) {
      $errors.Add("line ${lineNo}: field rule needs <owner.Fqn>.<NAME> and an expression starting with a class FQN: $raw"); continue
    }
    $field = Get-FieldRule $old $new
    $pattern = $field.FqnPattern
  }
  else { $errors.Add("line ${lineNo}: unknown kind '$kind' (expected 'token', 'literal', 'class' or 'field'): $raw"); continue }
  $rules.Add([pscustomobject]@{
      Index = $rules.Count + 1; Line = $lineNo; Kind = $kind; Old = $old; New = $new
      Regex = [regex]::new($pattern, $opts); Class = $class; Field = $field
      Hits = 0; Files = 0
    })
}
if ($errors.Count -gt 0) {
  Write-Host "ERROR: bad map syntax in ${Map}:"
  $errors | ForEach-Object { Write-Host "  $_" }
  exit 2
}
if ($rules.Count -eq 0) { Write-Host "ERROR: map has no rules: $Map"; exit 2 }

# ---------- collect files ----------
function ConvertTo-GlobRegex([string] $glob) {
  $g = $glob.Replace('\', '/').TrimStart('/')
  $sb = [System.Text.StringBuilder]::new('^')
  for ($i = 0; $i -lt $g.Length; $i++) {
    $c = $g[$i]
    if ($c -eq '*') {
      if ($i + 1 -lt $g.Length -and $g[$i + 1] -eq '*') {
        if ($i + 2 -lt $g.Length -and $g[$i + 2] -eq '/') { [void]$sb.Append('(?:.*/)?'); $i += 2 }
        else { [void]$sb.Append('.*'); $i += 1 }
      }
      else { [void]$sb.Append('[^/]*') }
    }
    elseif ($c -eq '?') { [void]$sb.Append('[^/]') }
    else { [void]$sb.Append([regex]::Escape([string]$c)) }
  }
  [void]$sb.Append('$')
  [regex]::new($sb.ToString(), 'IgnoreCase')
}

$globs = @($Include | ForEach-Object { $_ -split ',' } | ForEach-Object { $_.Trim() } | Where-Object { $_ })
$files = [System.Collections.Generic.SortedSet[string]]::new([System.StringComparer]::OrdinalIgnoreCase)
foreach ($glob in $globs) {
  $norm = $glob.Replace('\', '/').TrimStart('/')
  # Walk only from the literal directory prefix (e.g. 'src'), not the whole repo (build/, run/ are big).
  $segments = $norm -split '/'
  $prefix = @()
  for ($k = 0; $k -lt $segments.Count - 1; $k++) { if ($segments[$k] -match '[*?]') { break }; $prefix += $segments[$k] }
  $start = if ($prefix.Count) { Join-Path $Root ($prefix -join '\') } else { $Root }
  if (-not (Test-Path -LiteralPath $start -PathType Container)) { continue }
  $rx = ConvertTo-GlobRegex $norm
  foreach ($f in Get-ChildItem -LiteralPath $start -Recurse -File -Force) {
    $rel = $f.FullName.Substring($Root.Length + 1).Replace('\', '/')
    if ($rx.IsMatch($rel)) { [void]$files.Add($f.FullName) }
  }
}

# top-level classes per package of the scanned sources (file name = class), for the field rules' simple-name clash check
$typesByPkg = @{}
if (@($rules | Where-Object { $_.Field }).Count -gt 0) {
  $pkgRx = [regex]::new('(?m)^\s*package\s+([\w.]+)\s*;')
  foreach ($path in $files) {
    if (-not $path.EndsWith('.java', [System.StringComparison]::OrdinalIgnoreCase)) { continue }
    $m = $pkgRx.Match([System.IO.File]::ReadAllText($path))
    $p = if ($m.Success) { $m.Groups[1].Value } else { '' }
    if (-not $typesByPkg.ContainsKey($p)) { $typesByPkg[$p] = [System.Collections.Generic.HashSet[string]]::new() }
    [void]$typesByPkg[$p].Add([System.IO.Path]::GetFileNameWithoutExtension($path))
  }
}

# ---------- string-literal heuristic ----------
# True when position $pos (on its line) is inside a "..." string: scans the line prefix, honouring
# backslash escapes inside strings and skipping char literals such as '"'.
function Test-InString([string] $content, [int] $pos) {
  $lineStart = if ($pos -gt 0) { $content.LastIndexOf("`n", $pos - 1) + 1 } else { 0 }
  $inString = $false
  $i = $lineStart
  while ($i -lt $pos) {
    $c = $content[$i]
    if ($inString) {
      if ($c -eq '\') { $i += 2; continue }
      if ($c -eq '"') { $inString = $false }
    }
    elseif ($c -eq '"') { $inString = $true }
    elseif ($c -eq "'") {
      # skip a char literal: 'x' or '\x' (only if it closes within a few chars)
      $j = $i + 1
      if ($j -lt $content.Length -and $content[$j] -eq '\') { $j += 2 } else { $j += 1 }
      while ($j -lt $content.Length -and $j -lt $i + 8 -and $content[$j] -ne "'" -and $content[$j] -ne "`n") { $j++ }
      if ($j -lt $content.Length -and $content[$j] -eq "'" -and $j -lt $pos) { $i = $j + 1; continue }
    }
    $i++
  }
  return $inString
}

# True when $pos is inside a comment: after a '//' that is not in a string on its line, or after an unclosed '/*'
# (heuristic: '/*' inside a string literal is not excluded).
function Test-InComment([string] $content, [int] $pos) {
  $ord = [System.StringComparison]::Ordinal
  $open = if ($pos -gt 0) { $content.LastIndexOf('/*', $pos - 1, $ord) } else { -1 }
  if ($open -ge 0 -and $content.LastIndexOf('*/', $pos - 1, $ord) -lt $open) { return $true }
  $lineStart = if ($pos -gt 0) { $content.LastIndexOf("`n", $pos - 1, $ord) + 1 } else { 0 }
  $k = $lineStart
  while (($k = $content.IndexOf('//', $k, $ord)) -ge 0 -and $k -lt $pos) {
    if (-not (Test-InString $content $k)) { return $true }
    $k += 2
  }
  return $false
}

function Get-LineInfo([string] $content, [int] $pos) {
  $lineStart = if ($pos -gt 0) { $content.LastIndexOf("`n", $pos - 1) + 1 } else { 0 }
  $lineEnd = $content.IndexOf("`n", $pos)
  if ($lineEnd -lt 0) { $lineEnd = $content.Length }
  $number = 1
  for ($k = 0; $k -lt $lineStart; $k++) { if ($content[$k] -eq "`n") { $number++ } }
  [pscustomobject]@{ Number = $number; Text = $content.Substring($lineStart, $lineEnd - $lineStart).Trim() }
}

# ---------- apply rules ----------
$utf8Strict = [System.Text.UTF8Encoding]::new($false, $true)
$fileHits = [System.Collections.Generic.List[object]]::new()
$stringHits = [System.Collections.Generic.List[object]]::new()
$fieldNotes = [System.Collections.Generic.List[object]]::new()
$unreadable = [System.Collections.Generic.List[string]]::new()
$written = 0

foreach ($path in $files) {
  $rel = $path.Substring($Root.Length + 1).Replace('\', '/')
  $bytes = [System.IO.File]::ReadAllBytes($path)
  $hasBom = $bytes.Length -ge 3 -and $bytes[0] -eq 0xEF -and $bytes[1] -eq 0xBB -and $bytes[2] -eq 0xBF
  $offset = if ($hasBom) { 3 } else { 0 }
  try { $content = $utf8Strict.GetString($bytes, $offset, $bytes.Length - $offset) }
  catch { $unreadable.Add($rel); continue }

  $original = $content
  $hitsInFile = 0
  $newImports = [System.Collections.Generic.List[string]]::new()
  $pkgMatch = [regex]::Match($content, '(?m)^\s*package\s+([\w.]+)\s*;')
  $filePkg = if ($pkgMatch.Success) { $pkgMatch.Groups[1].Value } else { '' }
  foreach ($rule in $rules) {
    # (regex, replacement[, imports]) steps: one for token/literal; for class the FQN step plus the simple-name steps, whose
    # import conditions are checked on the content before this rule touches it; for field the FQN step plus the
    # qualified-name steps in files importing the old owner (their expression imports what it names)
    $steps = [System.Collections.Generic.List[object]]::new()
    if ($rule.Field) {
      $fr = $rule.Field
      $steps.Add(@($rule.Regex, $fr.NewFull, $null))
      $expr = $null
      foreach ($q in $fr.Quals) {
        if (-not $q.Import.IsMatch($content)) { continue }
        if (-not $expr) { $expr = Get-FieldExpression $fr $content $filePkg }
        $steps.Add(@($q.Pattern, $expr.Text, $expr.Imports))
      }
      if (-not $fr.SimpleExpr -and $fr.StaticImport.IsMatch($content)) {
        $info = Get-LineInfo $content $fr.StaticImport.Match($content).Index
        $fieldNotes.Add([pscustomobject]@{ File = $rel; Line = $info.Number; Rule = $rule.Index; Text = "static import of $($rule.Old) not rewritten (the replacement is an expression): fix by hand" })
      }
    }
    else { $steps.Add(@($rule.Regex, $rule.New, $null)) }
    if ($rule.Class) {
      $cl = $rule.Class
      if ($cl.Qual -and $cl.OuterImport.IsMatch($content)) { $steps.Add(@($cl.Qual, $cl.NewQual, $null)) }
      if ($cl.Simple -and $cl.Import.IsMatch($content)) { $steps.Add(@($cl.Simple, $cl.NewSimple, $null)) }
    }
    $ruleHits = 0
    foreach ($step in $steps) {
      $matches_ = $step[0].Matches($content)
      if ($matches_.Count -eq 0) { continue }
      $codeHits = 0
      foreach ($m in $matches_) {
        if (Test-InString $content $m.Index) {
          $info = Get-LineInfo $content $m.Index
          $stringHits.Add([pscustomobject]@{ File = $rel; Line = $info.Number; Rule = $rule.Index; Old = $rule.Old; Text = $info.Text })
        }
        elseif (-not (Test-InComment $content $m.Index)) { $codeHits++ }
      }
      $ruleHits += $matches_.Count
      $content = $step[0].Replace($content, $step[1].Replace('$', '$$'))
      # imports only for code hits: a rewrite inside a string or comment needs none
      if ($codeHits -eq 0) { continue }
      # 'Outer.Inner' now names another top-level class: import it (after all rules, so line numbers stay put)
      if ($rule.Class -and $step[0] -eq $rule.Class.Qual -and $rule.Class.NewTopImport) { [void]$newImports.Add($rule.Class.NewTopImport) }
      if ($step[2]) { foreach ($imp in $step[2]) { if (-not $newImports.Contains($imp)) { [void]$newImports.Add($imp) } } }
    }
    if ($ruleHits -eq 0) { continue }
    $rule.Hits += $ruleHits
    $rule.Files++
    $hitsInFile += $ruleHits
  }

  foreach ($imp in $newImports) {
    if ($content.Contains($imp)) { continue }
    $eol = if ($content.Contains("`r`n")) { "`r`n" } else { "`n" }
    $last = [regex]::Matches($content, '(?m)^import\s+[^;\r\n]+;') | Select-Object -Last 1
    if ($last) { $content = $content.Insert($last.Index + $last.Length, $eol + $imp) }
  }
  if ($hitsInFile -gt 0) { $fileHits.Add([pscustomobject]@{ File = $rel; Hits = $hitsInFile }) }
  if ($Apply -and $content -ne $original) {
    $out = $utf8Strict.GetBytes($content)
    if ($hasBom) { $out = [byte[]](0xEF, 0xBB, 0xBF) + $out }
    [System.IO.File]::WriteAllBytes($path, $out)
    $written++
  }
}

# ---------- report ----------
$mode = if ($Apply) { 'APPLY' } else { 'DRY RUN (nothing written; pass -Apply to rewrite)' }
Write-Host "rename-map: $mode"
Write-Host "  root:    $Root"
Write-Host "  map:     $Map"
Write-Host "  include: $($globs -join ', ')  ($($files.Count) files scanned)"
Write-Host ''
Write-Host 'Hits per rule:'
$rules | Format-Table @{N = '#'; E = { $_.Index } }, Kind, Old, New, Hits, Files -AutoSize | Out-String -Width 220 | Write-Host

$totalHits = ($rules | Measure-Object Hits -Sum).Sum
Write-Host "Hits per file (top $Top of $($fileHits.Count) files):"
$fileHits | Sort-Object @{E = 'Hits'; Descending = $true }, File | Select-Object -First $Top |
  Format-Table Hits, File -AutoSize | Out-String -Width 220 | Write-Host

if ($stringHits.Count -gt 0) {
  Write-Host "WARNING: $($stringHits.Count) hit(s) inside a string literal (heuristic; counted and replaced anyway - review):"
  foreach ($h in $stringHits) { Write-Host ("  {0}:{1}  [rule {2} {3}]  {4}" -f $h.File, $h.Line, $h.Rule, $h.Old, $h.Text) }
  Write-Host ''
}
if ($fieldNotes.Count -gt 0) {
  Write-Host "WARNING: $($fieldNotes.Count) field-rule spot(s) left for a manual fix:"
  foreach ($h in $fieldNotes) { Write-Host ("  {0}:{1}  [rule {2}]  {3}" -f $h.File, $h.Line, $h.Rule, $h.Text) }
  Write-Host ''
}
if ($unreadable.Count -gt 0) {
  Write-Host "WARNING: $($unreadable.Count) file(s) skipped (not valid UTF-8):"
  $unreadable | ForEach-Object { Write-Host "  $_" }
  Write-Host ''
}
if ($Apply) { Write-Host "written=$written" }
Write-Host "rules=$($rules.Count) files=$($fileHits.Count) hits=$totalHits stringHits=$($stringHits.Count)"
if ($unreadable.Count -gt 0) { exit 1 }
exit 0
